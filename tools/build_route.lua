-- Build data/Route.lua: the ORDER of quests in a levelling route, nothing else.
--   lua tools/build_route.lua <Alliance route text> <Horde route text> <out file>
-- The route files are PoleStar's 1-60 guides as converted for OpenXP 2.0 (both GPL-3.0). They are only READ AS TEXT here, never run:
-- the converter looks for the "accept" and "turnin" steps and keeps the quest number, a class limit and an "optional" flag.
--   https://github.com/fitzforge/polestar  (route)    https://github.com/mjared123/OpenXP  (conversion)
local ALLI, HORDE, OUT = arg[1], arg[2], arg[3]
assert(OUT, "usage: lua build_route.lua <Alliance text> <Horde text> <out file>")

local function Read(path)
    local f = assert(io.open(path, "rb")); local t = f:read("*a"); f:close(); return t
end

local function Parse(text)
    local guides, cur = {}, nil
    for line in (text .. "\n"):gmatch("([^\r\n]*)\r?\n") do
        local name = line:match('^    name = "(.-)",')
        if name then
            cur = { name = name, steps = {} }
            guides[#guides + 1] = cur
        elseif cur then
            local only = line:match('^    only = "(.-)",')
            if only then cur.only = only end
            local nxt = line:match('^    next = "(.-)",')
            if nxt then cur.next = nxt end
            -- a step: { "accept", [only = "Warlock",] [optional = true,] quest = 123, ... }
            local kind, rest = line:match('^%s+{ "(%a+)",(.*)$')
            if kind == "accept" or kind == "turnin" then
                local id = rest:match("quest = (%d+)")
                if id then
                    local tok = (kind == "accept" and "a" or "t") .. id
                    local cls = rest:match('only = "(%a+)"')
                    if cls then tok = tok .. "!" .. cls end
                    if rest:find("optional = true", 1, true) then tok = tok .. "?" end
                    cur.steps[#cur.steps + 1] = tok
                end
            end
        end
    end
    return guides
end

local function Emit(o, faction, guides)
    o[#o + 1] = string.format("  %s = {\n", faction)
    local n, tokens = 0, 0
    for _, g in ipairs(guides) do
        if #g.steps > 0 then
            n = n + 1; tokens = tokens + #g.steps
            o[#o + 1] = string.format("    { name = %q, only = %q, steps = %q },\n", g.name, g.only or faction, table.concat(g.steps, " "))
        end
    end
    o[#o + 1] = "  },\n"
    return n, tokens
end

local o = {}
o[#o + 1] = "-- The order of quests in a 1-60 levelling route, per faction. Generated by tools/build_route.lua: do not edit.\n"
o[#o + 1] = "-- Route adapted from PoleStar's guides (https://github.com/fitzforge/polestar, GPL-3.0) as converted for OpenXP 2.0\n"
o[#o + 1] = "-- (https://github.com/mjared123/OpenXP, GPL-3.0). Only the quest numbers and their order are kept here; see media/CREDITS.txt.\n"
o[#o + 1] = "-- steps: a123 = accept quest 123, t123 = turn it in, !Class = only that class, ? = optional.\n"
o[#o + 1] = "local ADDON, ns = ...\nns.dataset.route = {\n"
local a, at = Emit(o, "Alliance", Parse(Read(ALLI)))
local h, ht = Emit(o, "Horde", Parse(Read(HORDE)))
o[#o + 1] = "}\n"
local f = assert(io.open(OUT, "wb")); f:write(table.concat(o)); f:close()
print(string.format("Alliance: %d guides, %d steps   Horde: %d guides, %d steps   written %s", a, at, h, ht, OUT))
